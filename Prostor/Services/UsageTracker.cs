using System.Text.RegularExpressions;
using Microsoft.Win32;
using Prostor.Core;
using Prostor.Models;

namespace Prostor.Services;

/// <summary>Where Windows remembers program launches.</summary>
public sealed class UsageData
{
    /// <summary>Full exe path → last launch (UserAssist: Start menu, taskbar, Explorer).</summary>
    public Dictionary<string, DateTime> ByPath { get; } = new(StringComparer.OrdinalIgnoreCase);
    /// <summary>Package family name → last launch (Store apps).</summary>
    public Dictionary<string, DateTime> ByPackage { get; } = new(StringComparer.OrdinalIgnoreCase);
    /// <summary>EXE name (upper case, as in Prefetch) → last launch. Covers any launch, needs admin rights.</summary>
    public Dictionary<string, DateTime> ByExeName { get; } = new(StringComparer.OrdinalIgnoreCase);
    /// <summary>App user model IDs that could not be tied to a file.</summary>
    public List<(string Id, DateTime Time)> Unresolved { get; } = new();
    /// <summary>Steam app id → last played.</summary>
    public Dictionary<string, DateTime> SteamLastPlayed { get; } = new();

    public bool HasPrefetch => ByExeName.Count > 0;
}

/// <summary>Finds out when each program was last started (UserAssist, Prefetch, Steam).</summary>
public static class UsageTracker
{
    private static readonly string[] UserAssistKeys =
    {
        @"Software\Microsoft\Windows\CurrentVersion\Explorer\UserAssist\{CEBFF5CD-ACE2-4F4F-9178-9926F41749EA}\Count",
        @"Software\Microsoft\Windows\CurrentVersion\Explorer\UserAssist\{F4E57C4B-2036-45F0-A9AB-443BCFE33D9F}\Count",
    };

    private static readonly Regex HelperExe = new(@"unins|uninst|setup|install|update|updater|crash|report|helper|elevat|vc_?redist|dotnet",
        RegexOptions.IgnoreCase | RegexOptions.Compiled);

    public static UsageData Load()
    {
        var data = new UsageData();
        Dictionary<string, (string target, string aumid)> shortcuts = null;
        RunSta(() => shortcuts = ShortcutIndex());
        shortcuts ??= new(StringComparer.OrdinalIgnoreCase);
        var byAumid = shortcuts.Values.Where(s => !string.IsNullOrEmpty(s.aumid) && !string.IsNullOrEmpty(s.target))
            .GroupBy(s => s.aumid, StringComparer.OrdinalIgnoreCase)
            .ToDictionary(g => g.Key, g => g.First().target, StringComparer.OrdinalIgnoreCase);

        foreach (var key in UserAssistKeys)
        {
            try
            {
                using var k = Registry.CurrentUser.OpenSubKey(key);
                if (k == null) continue;
                foreach (var raw in k.GetValueNames())
                {
                    if (k.GetValue(raw) is not byte[] { Length: >= 68 } bytes) continue;
                    long ft = BitConverter.ToInt64(bytes, 60);
                    if (ft <= 0) continue;
                    DateTime time;
                    try { time = DateTime.FromFileTime(ft); }
                    catch { continue; }
                    if (time.Year < 2000 || time > DateTime.Now.AddDays(1)) continue;
                    AddEntry(data, Rot13(raw), time, shortcuts, byAumid);
                }
            }
            catch { }
        }

        if (ShellHelper.IsAdmin) ReadPrefetch(data);
        ReadSteam(data);
        return data;
    }

    private static void AddEntry(UsageData data, string name, DateTime time,
        Dictionary<string, (string target, string aumid)> shortcuts, Dictionary<string, string> byAumid)
    {
        if (name.StartsWith("UEME_", StringComparison.Ordinal)) return;
        string path = ExpandKnownFolder(name);
        if (path != null)
        {
            if (path.EndsWith(".lnk", StringComparison.OrdinalIgnoreCase))
            {
                if (!shortcuts.TryGetValue(path, out var sc) || string.IsNullOrEmpty(sc.target)) return;
                path = sc.target;
            }
            Put(data.ByPath, path, time);
            return;
        }
        int bang = name.IndexOf('!');
        if (bang > 0 && name.Contains('_'))
        {
            Put(data.ByPackage, name.Substring(0, bang), time); // PackageFamilyName!AppId
            return;
        }
        if (byAumid.TryGetValue(name, out var target))
        {
            Put(data.ByPath, target, time);
            return;
        }
        if (!name.StartsWith("Microsoft.AutoGenerated", StringComparison.OrdinalIgnoreCase))
            data.Unresolved.Add((name, time));
    }

    private static void Put(Dictionary<string, DateTime> map, string key, DateTime time)
    {
        if (!map.TryGetValue(key, out var old) || old < time) map[key] = time;
    }

    /// <summary>"{6D809377-...}\App\app.exe" → "C:\Program Files\App\app.exe"; plain paths pass through.</summary>
    private static string ExpandKnownFolder(string name)
    {
        if (name.Length > 3 && name[1] == ':' && name[2] == '\\') return name;
        if (name.Length > 39 && name[0] == '{' && name[37] == '}' && Guid.TryParse(name.AsSpan(1, 36), out var g))
        {
            string folder = KnownFolder(g);
            return folder == null ? null : folder + name.Substring(38);
        }
        return null;
    }

    private static readonly Dictionary<Guid, string> KnownFolders = new();

    private static string KnownFolder(Guid id)
    {
        lock (KnownFolders)
        {
            if (KnownFolders.TryGetValue(id, out var cached)) return cached;
            string path = null;
            try
            {
                if (Native.SHGetKnownFolderPath(id, 0, IntPtr.Zero, out var p) == 0)
                {
                    path = System.Runtime.InteropServices.Marshal.PtrToStringUni(p);
                    System.Runtime.InteropServices.Marshal.FreeCoTaskMem(p);
                }
            }
            catch { }
            KnownFolders[id] = path;
            return path;
        }
    }

    public static string Rot13(string s)
    {
        var c = s.ToCharArray();
        for (int i = 0; i < c.Length; i++)
        {
            char ch = c[i];
            if (ch is >= 'a' and <= 'z') c[i] = (char)('a' + (ch - 'a' + 13) % 26);
            else if (ch is >= 'A' and <= 'Z') c[i] = (char)('A' + (ch - 'A' + 13) % 26);
        }
        return new string(c);
    }

    /// <summary>Start menu and taskbar shortcuts: their target and AppUserModelID.</summary>
    private static Dictionary<string, (string target, string aumid)> ShortcutIndex()
    {
        var result = new Dictionary<string, (string, string)>(StringComparer.OrdinalIgnoreCase);
        var type = Type.GetTypeFromProgID("Shell.Application");
        if (type == null) return result;
        dynamic shell = Activator.CreateInstance(type);
        string[] roots =
        {
            Environment.GetFolderPath(Environment.SpecialFolder.CommonPrograms),
            Environment.GetFolderPath(Environment.SpecialFolder.Programs),
            Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), @"Microsoft\Internet Explorer\Quick Launch"),
            Environment.GetFolderPath(Environment.SpecialFolder.Desktop),
            Environment.GetFolderPath(Environment.SpecialFolder.CommonDesktopDirectory),
        };
        foreach (var root in roots.Where(r => !string.IsNullOrEmpty(r) && Directory.Exists(r)))
        {
            IEnumerable<string> files;
            try
            {
                files = Directory.EnumerateFiles(root, "*.lnk", new EnumerationOptions { RecurseSubdirectories = true, IgnoreInaccessible = true });
            }
            catch { continue; }
            foreach (var lnk in files)
            {
                try
                {
                    dynamic folder = shell.NameSpace(Path.GetDirectoryName(lnk));
                    dynamic item = folder?.ParseName(Path.GetFileName(lnk));
                    if (item == null) continue;
                    string target = item.ExtendedProperty("System.Link.TargetParsingPath") as string;
                    string aumid = item.ExtendedProperty("System.AppUserModel.ID") as string;
                    if (string.IsNullOrEmpty(target) || !target.EndsWith(".exe", StringComparison.OrdinalIgnoreCase)) target = null;
                    result[lnk] = (target, aumid);
                }
                catch { }
            }
        }
        return result;
    }

    private static void ReadPrefetch(UsageData data)
    {
        try
        {
            string dir = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.Windows), "Prefetch");
            foreach (var f in new DirectoryInfo(dir).EnumerateFiles("*.pf"))
            {
                int dash = f.Name.LastIndexOf('-');
                if (dash <= 0) continue;
                Put(data.ByExeName, f.Name.Substring(0, dash), f.LastWriteTime);
            }
        }
        catch { }
    }

    private static void ReadSteam(UsageData data)
    {
        try
        {
            string steam = SteamLibrary.SteamPath;
            if (steam == null) return;
            string userdata = Path.Combine(steam, "userdata");
            if (!Directory.Exists(userdata)) return;
            foreach (var user in Directory.GetDirectories(userdata))
            {
                string cfg = Path.Combine(user, "config", "localconfig.vdf");
                if (!File.Exists(cfg)) continue;
                var root = SteamLibrary.Parse(File.ReadAllText(cfg));
                if (Dig(root, "UserLocalConfigStore", "Software", "Valve", "Steam", "apps") is not Dictionary<string, object> apps) continue;
                foreach (var (id, value) in apps)
                {
                    if (value is not Dictionary<string, object> app || !app.TryGetValue("LastPlayed", out var lp) ||
                        !long.TryParse(lp as string, out long unix) || unix <= 0) continue;
                    var t = DateTimeOffset.FromUnixTimeSeconds(unix).LocalDateTime;
                    if (!data.SteamLastPlayed.TryGetValue(id, out var old) || old < t) data.SteamLastPlayed[id] = t;
                }
            }
        }
        catch { }
    }

    private static object Dig(Dictionary<string, object> d, params string[] path)
    {
        object cur = d;
        foreach (var p in path)
        {
            if (cur is not Dictionary<string, object> dict || !dict.TryGetValue(p, out cur)) return null;
        }
        return cur;
    }

