    /// <summary>Last launch of the program, or null when Windows has no record of it.</summary>
    public static DateTime? LastUsed(InstalledApp app, UsageData data)
    {
        DateTime? best = null;
        void Take(DateTime t)
        {
            if (best == null || t > best) best = t;
        }

        if (app.IsStore)
        {
            if (app.PackageFamilyName != null && data.ByPackage.TryGetValue(app.PackageFamilyName, out var t)) Take(t);
            return best;
        }
        if (app.SteamAppId != null && data.SteamLastPlayed.TryGetValue(app.SteamAppId, out var played)) Take(played);

        string location = app.InstallLocation?.TrimEnd('\\');
        if (!string.IsNullOrEmpty(location))
        {
            string prefix = location + "\\";
            foreach (var (path, t) in data.ByPath)
            {
                if (path.StartsWith(prefix, StringComparison.OrdinalIgnoreCase) && !HelperExe.IsMatch(Path.GetFileName(path))) Take(t);
            }
            if (data.HasPrefetch)
            {
                foreach (var exe in ExecutablesIn(location))
                {
                    string upper = exe.ToUpperInvariant();
                    if (data.ByExeName.TryGetValue(upper, out var t)) Take(t);
                    else if (upper.Length > 29 && data.ByExeName.TryGetValue(upper.Substring(0, 29), out t)) Take(t);
                }
            }
        }

        string norm = Normalize(app.Name);
        if (norm.Length >= 4)
        {
            foreach (var (id, t) in data.Unresolved)
            {
                string n = Normalize(id);
                if (n.Contains(norm) || (n.Length >= 6 && norm.Contains(n))) Take(t);
            }
        }
        return best;
    }

    private static readonly Dictionary<string, List<string>> ExeCache = new(StringComparer.OrdinalIgnoreCase);

    /// <summary>EXE names in the program folder (two levels deep), helpers and uninstallers excluded.</summary>
    private static List<string> ExecutablesIn(string folder)
    {
        lock (ExeCache)
        {
            if (ExeCache.TryGetValue(folder, out var cached)) return cached;
        }
        var list = new List<string>();
        void Scan(string dir, int depth)
        {
            if (list.Count > 300) return;
            try
            {
                foreach (var f in Directory.EnumerateFiles(dir, "*.exe"))
                {
                    string n = Path.GetFileName(f);
                    if (!HelperExe.IsMatch(n)) list.Add(n);
                }
                if (depth < 2)
                    foreach (var d in Directory.EnumerateDirectories(dir)) Scan(d, depth + 1);
            }
            catch { }
        }
        Scan(folder, 0);
        lock (ExeCache) ExeCache[folder] = list;
        return list;
    }

    private static string Normalize(string s) =>
        new string((s ?? "").Where(char.IsLetterOrDigit).ToArray()).ToLowerInvariant();

    private static void RunSta(Action action)
    {
        var t = new Thread(() =>
        {
            try { action(); }
            catch { }
        });
        t.SetApartmentState(ApartmentState.STA);
        t.IsBackground = true;
        t.Start();
        t.Join(TimeSpan.FromSeconds(20));
    }
}
